#!/usr/bin/env bash
# P19 (ADR-0027): OWASP ZAP baseline (passive) against the running gateway, as a signed-in demo user.
# A ZAP hook signs every request with the user's bearer token and seeds the API's GET routes (a JSON API gives the
# spider nothing to follow), so the passive rules see real authenticated and public responses.
# Rules: infra/security/zap-rules.tsv (FAIL fails the scan). Reports: target/verify/zap/{zap.html,zap.json,zap.md}.
set -uo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
GW=${GATEWAY_URL:-http://127.0.0.1:8080}
IMAGE=${ZAP_IMAGE:-ghcr.io/zaproxy/zaproxy:2.16.1}
OUT="$ROOT/target/verify/zap"
[[ -f "$ROOT/.env" ]] && { set -a; source "$ROOT/.env"; set +a; }
rm -rf "$OUT"; mkdir -p "$OUT"; chmod 777 "$OUT"
cp "$ROOT/infra/security/zap-rules.tsv" "$OUT/rules.tsv"

token=$(curl -fsS --max-time 10 -H 'Content-Type: application/json' \
  -d "{\"email\":\"asha@demo.in\",\"password\":\"${DEMO_PASSWORD_ASHA:-}\"}" "$GW/v1/auth/login" \
  | python3 -c 'import json,sys; print(json.load(sys.stdin)["accessToken"])') \
  || { echo "FAIL: could not sign in asha@demo.in through the gateway"; exit 1; }

cat > "$OUT/hook.py" <<PY
# ZAP baseline hook (generated by scripts/zap-baseline.sh)
SEEDS = """
/v1/me
/v1/me/sessions
/v1/expenses?limit=5
/v1/categories
/v1/merchants/search?q=amazon
/v1/summary
/v1/cards
/v1/emi-plans
/v1/budgets
/v1/liabilities
/v1/scenarios
/v1/recommendations
/v1/plans
/v1/entitlements/me
/v1/invoices
/v1/deals
/v1/card-applications
/v1/notifications
/v1/notification-prefs
/v1/catalog/issuers
/v1/catalog/cards?limit=5
/v1/auth/login
/v1/does-not-exist
/actuator/health
""".split()

def zap_started(zap, target):
    zap.replacer.add_rule(description="bearer", enabled=True, matchtype="REQ_HEADER", matchregex=False,
                          matchstring="Authorization", replacement="Bearer ${token}")
    for path in SEEDS:
        zap.core.access_url("${GW}" + path, followredirects=False)

def zap_pre_shutdown(zap):
    urls = zap.core.urls()
    with open("/zap/wrk/urls.txt", "w") as f:
        f.write("\n".join(urls))
PY

status=0
timeout -k 20 900 docker run --rm --network host -v "$OUT:/zap/wrk:rw" "$IMAGE" \
  zap-baseline.py -t "$GW/v1/me" -c rules.tsv --hook=/zap/wrk/hook.py -m 1 -I \
  -J zap.json -r zap.html -w zap.md > "$OUT/zap.log" 2>&1 || status=$?
tail -n 25 "$OUT/zap.log"
python3 - "$OUT" "$status" <<'PY'
import json, pathlib, sys
out, status = pathlib.Path(sys.argv[1]), int(sys.argv[2])
urls = [u for u in (out / "urls.txt").read_text().split() if u] if (out / "urls.txt").exists() else []
alerts = []
if (out / "zap.json").exists():
    for site in json.loads((out / "zap.json").read_text()).get("site", []):
        alerts += site.get("alerts", [])
rules = {l.split("\t")[0]: l.split("\t")[1] for l in (out / "rules.tsv").read_text().splitlines()
         if l and not l.startswith("#")}
fails = [a for a in alerts if rules.get(a.get("pluginid")) == "FAIL"]
print(f"zap: {len(urls)} URLs scanned, {len(alerts)} alert types "
      f"({', '.join(sorted(a['pluginid'] + ':' + a['riskdesc'].split()[0] for a in alerts)) or 'none'}), "
      f"{len(fails)} FAIL-level, exit {status}")
# Not a test unless the scan saw the API: at least the seeded routes must have been requested.
ok = status in (0,) and len(urls) >= 15 and not fails
if len(urls) < 15:
    print(f"FAIL: only {len(urls)} URLs reached ZAP - the hook did not seed the API")
sys.exit(0 if ok else 1)
PY
