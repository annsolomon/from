#!/usr/bin/env bash
# Renders infra/postgres/init/00-roles.sql.tmpl once per service in DEXTER_DB_SERVICES and prints
# SQL (psql dialect) to stdout. DEV ONLY. Passwords: PG_PW_<SERVICE>_<ROLE>, else PG_PW_<ROLE>.
#   Inspect on the host:  set -a; . ./.env; set +a; bash infra/postgres/render-roles.sh
set -euo pipefail

die() { echo "render-roles: $*" >&2; exit 1; }

tmpl="${1:-$(cd "$(dirname "$0")" && pwd)/init/00-roles.sql.tmpl}"
[[ -r "$tmpl" ]] || die "template not readable: $tmpl"
[[ -n "${DEXTER_DB_SERVICES:-}" ]] || die "DEXTER_DB_SERVICES is empty (see .env.example)"

template=$(<"$tmpl")
echo "-- GENERATED by render-roles.sh - do not commit the output"
echo '\set ON_ERROR_STOP on'
for svc in $DEXTER_DB_SERVICES; do
  [[ "$svc" =~ ^[a-z][a-z0-9_]{1,30}$ ]] || die "invalid service name: $svc"
  out=$template
  out=${out//"{{svc}}"/"$svc"}
  for role in owner app admin relay readonly; do
    specific="PG_PW_${svc^^}_${role^^}"
    generic="PG_PW_${role^^}"
    pw="${!specific:-${!generic:-}}"
    [[ -n "$pw" ]] || die "no password for ${svc}_${role}: set $generic (or $specific)"
    pw=${pw//\'/\'\'}                       # SQL-escape single quotes
    out=${out//"{{pw_${role}}}"/"$pw"}
  done
  [[ "$out" != *"{{"* ]] || die "unrendered placeholder left for $svc"
  printf '%s\n\n' "$out"
done
